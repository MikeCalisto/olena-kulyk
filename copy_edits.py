def apply(html):
    """Застосовує правки, падаючи на першому ж фрагменті, якого немає або є двічі."""
    for old, new in EDITS:
        n = html.count(old)
        if n != 1:
            raise SystemExit(f"правка не застосована ({n} збігів): {old[:70]!r}")
        html = html.replace(old, new, 1)
    return html
